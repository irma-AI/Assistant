-- Voucher guard. SECURITY DEFINER so the series row can stay out of the app role's reach; row level security still
-- applies to the owner (FORCE), and the transaction's organisation setting is what lets it through.
create function vouchers_guard() returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
declare
  fy fiscal_years;
begin
  if tg_op = 'INSERT' then
    if new.status <> 'draft' then
      raise exception 'a voucher starts as a draft' using errcode = 'restrict_violation';
    end if;
    return new;
  end if;
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception 'voucher % is posted and cannot be deleted', old.id using errcode = 'restrict_violation';
    end if;
    return old;
  end if;

  if old.status = 'draft' and new.status = 'draft' then
    return new;
  end if;

  if old.status = 'draft' and new.status = 'posted' then
    select * into fy from fiscal_years where organisation_id = new.organisation_id and id = new.fiscal_year_id;
    if new.voucher_date not between fy.starts_on and fy.ends_on then
      raise exception 'voucher date % is outside its fiscal year', new.voucher_date using errcode = 'check_violation';
    end if;
    if fy.locked_through is not null and new.voucher_date <= fy.locked_through then
      raise exception 'the period up to % is locked', fy.locked_through using errcode = 'restrict_violation';
    end if;
    if new.reverses_id is not null and
       (select status from vouchers where organisation_id = new.organisation_id and id = new.reverses_id) <> 'posted' then
      raise exception 'only a posted voucher can be reversed' using errcode = 'restrict_violation';
    end if;
    -- Lock and increment the series row in this transaction, so a rollback rolls the number back
    -- (BFNAR 2013:2 point 5.9). Whatever the caller sent is ignored.
    insert into voucher_counters (organisation_id, fiscal_year_id, last_number)
      values (new.organisation_id, new.fiscal_year_id, 1)
      on conflict (organisation_id, fiscal_year_id)
      do update set last_number = voucher_counters.last_number + 1
      returning last_number into new.number;
    new.posted_at := now();
    update documents set retain_until = fy.retain_until
      where organisation_id = new.organisation_id
        and id in (select document_id from voucher_documents where voucher_id = new.id);
    return new;
  end if;

  -- The one change a posted voucher takes: a storno marks it reversed.
  if old.status = 'posted' and new.status = 'reversed'
     and (to_jsonb(new) - 'status') = (to_jsonb(old) - 'status')
     and old.reverses_id is null
     and exists (select 1 from vouchers where organisation_id = old.organisation_id and reverses_id = old.id and status = 'posted') then
    return new;
  end if;

  raise exception 'voucher % is posted and immutable', old.id using errcode = 'restrict_violation';
end $$;

create trigger vouchers_guard before insert or update or delete on vouchers
  for each row execute function vouchers_guard();

-- Debit equals credit, and above zero, checked when the transaction commits.
create function vouchers_balanced() returns trigger language plpgsql as $$
declare
  d bigint;
  c bigint;
begin
  select coalesce(sum(debit), 0), coalesce(sum(credit), 0) into d, c from voucher_lines where voucher_id = new.id;
  if d <> c or d = 0 then
    raise exception 'voucher % is not balanced (debit %, credit %)', new.id, d, c using errcode = 'check_violation';
  end if;
  return null;
end $$;

create constraint trigger vouchers_balanced after insert or update on vouchers
  deferrable initially deferred for each row when (new.status <> 'draft') execute function vouchers_balanced();

-- Lines and underlag follow their voucher: free while it is a draft, frozen after.
create function voucher_children_guard() returns trigger language plpgsql as $$
declare
  s text;
begin
  select status into s from vouchers where id = coalesce(new.voucher_id, old.voucher_id);
  -- No parent row: the foreign key rejects an insert, and a cascade from a deleted draft passes.
  if s is not null and s <> 'draft' then
    raise exception 'voucher is posted and immutable' using errcode = 'restrict_violation';
  end if;
  return coalesce(new, old);
end $$;

create trigger voucher_lines_guard before insert or update or delete on voucher_lines
  for each row execute function voucher_children_guard();
create trigger voucher_documents_guard before insert or update or delete on voucher_documents
  for each row execute function voucher_children_guard();

do $$
declare
  t text;
begin
  foreach t in array array['fiscal_years', 'accounts', 'voucher_counters', 'vouchers', 'voucher_lines', 'voucher_documents', 'bookkeeping_history'] loop
    execute format('alter table %I enable row level security', t);
    execute format('alter table %I force row level security', t);
    execute format('create policy tenant on %I using (organisation_id = current_organisation_id()) with check (organisation_id = current_organisation_id())', t);
  end loop;
end $$;


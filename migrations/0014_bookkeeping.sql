-- Bookkeeping core (IRM-151), implementing docs/bookkeeping-foundations.md. The law is enforced here, by triggers and
-- constraints: a code path that hits one is wrong, not the trigger.

-- squawk-ignore require-concurrent-index-creation, ban-create-domain-with-constraint
create extension if not exists btree_gist;

-- Fiscal years (BFL 3 kap. 1-3 §): twelve months, a first or changed year shorter or under 18 months. They never
-- overlap. locked_through is the period lock: nothing is posted dated on or before it, and it only moves forward.
-- retain_until is 31 December of the seventh year after the calendar year the fiscal year ended (BFL 7 kap. 2 §).
create table fiscal_years (
  id uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references organisations (id) on delete cascade,
  starts_on date not null,
  ends_on date not null,
  locked_through date,
  retain_until date not null generated always as (make_date(extract(year from ends_on)::int + 7, 12, 31)) stored,
  created_at timestamptz not null default now(),
  unique (organisation_id, id),
  check (ends_on > starts_on and ends_on < (starts_on + interval '18 months')::date),
  check (locked_through is null or locked_through between starts_on and ends_on),
  exclude using gist (organisation_id with =, daterange(starts_on, ends_on, '[]') with &&)
);

create function fiscal_years_guard() returns trigger language plpgsql as $$
begin
  if (new.organisation_id, new.starts_on, new.ends_on) is distinct from (old.organisation_id, old.starts_on, old.ends_on) then
    raise exception 'fiscal year % dates are immutable', old.id using errcode = 'restrict_violation';
  end if;
  if old.locked_through is not null and (new.locked_through is null or new.locked_through < old.locked_through) then
    raise exception 'a period lock only moves forward' using errcode = 'restrict_violation';
  end if;
  return new;
end $$;

create trigger fiscal_years_guard before update on fiscal_years
  for each row execute function fiscal_years_guard();

-- The BAS chart as published (a version is part of the processing history, BFNAR 2013:2 point 9.16). Organisations
-- copy it into accounts, so the chart is data per organisation and per BAS version.
create table bas_versions (
  version text primary key,
  source text not null,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$')
);

create table bas_accounts (
  version text not null references bas_versions (version),
  number text not null check (number ~ '^[1-8][0-9]{3}$'),
  name text not null check (length(name) between 1 and 200),
  not_k2 boolean not null,
  primary key (version, number)
);

grant select on bas_versions, bas_accounts to assistant_app;

-- Account numbers are text. bas_version is null for an account the organisation added itself.
create table accounts (
  organisation_id uuid not null references organisations (id) on delete cascade,
  number text not null check (number ~ '^[1-8][0-9]{3}$'),
  name text not null check (length(name) between 1 and 200),
  not_k2 boolean not null default false,
  active boolean not null default true,
  bas_version text references bas_versions (version),
  primary key (organisation_id, number)
);

-- The voucher series: one row per organisation and fiscal year, only ever touched by vouchers_guard.
create table voucher_counters (
  organisation_id uuid not null,
  fiscal_year_id uuid not null,
  last_number bigint not null check (last_number > 0),
  primary key (organisation_id, fiscal_year_id),
  foreign key (organisation_id, fiscal_year_id) references fiscal_years (organisation_id, id)
);

-- Vouchers (verifikationer). A draft is freely editable and has no number; posting ("Bokför") numbers it and freezes
-- it. A correction is a storno: a new posted voucher with reverses_id set, after which the original reads reversed.
-- The author is kept by name and by users.id (RESTRICT), never erased with the account.
create table vouchers (
  id uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references organisations (id) on delete restrict,
  fiscal_year_id uuid not null,
  status text not null default 'draft' check (status in ('draft', 'posted', 'reversed')),
  number bigint check (number > 0),
  voucher_date date not null,
  description text not null check (length(description) between 1 and 500),
  created_by uuid not null references users (id) on delete restrict,
  created_by_name text not null,
  created_at timestamptz not null default now(),
  posted_by uuid references users (id) on delete restrict,
  posted_by_name text,
  posted_at timestamptz,
  app_version text,
  reverses_id uuid,
  unique (organisation_id, id),
  unique (organisation_id, fiscal_year_id, number),
  unique (organisation_id, reverses_id),
  foreign key (organisation_id, fiscal_year_id) references fiscal_years (organisation_id, id) on delete restrict,
  foreign key (organisation_id, reverses_id) references vouchers (organisation_id, id) on delete restrict,
  check ((status = 'draft') = (number is null)),
  check ((status = 'draft') = (posted_at is null)),
  check (status = 'draft' or (posted_by is not null and posted_by_name is not null and app_version is not null))
);

-- squawk-ignore require-concurrent-index-creation
create index vouchers_year_idx on vouchers (organisation_id, fiscal_year_id, number);

-- Amounts are whole öre in SEK.
create table voucher_lines (
  id uuid primary key default gen_random_uuid(),
  organisation_id uuid not null,
  voucher_id uuid not null,
  -- A position under 1000; bigint would reach Node as a string.
  -- squawk-ignore prefer-bigint-over-smallint
  line_no smallint not null check (line_no between 1 and 999),
  account text not null,
  debit bigint not null default 0 check (debit >= 0 and debit < 1000000000000000),
  credit bigint not null default 0 check (credit >= 0 and credit < 1000000000000000),
  text text check (length(text) between 1 and 200),
  unique (voucher_id, line_no),
  check ((debit > 0) <> (credit > 0)),
  foreign key (organisation_id, voucher_id) references vouchers (organisation_id, id) on delete cascade,
  foreign key (organisation_id, account) references accounts (organisation_id, number)
);

-- Underlag. A document backs one voucher; posting sets its retain_until, which freezes it (documents_guard).
-- squawk-ignore disallowed-unique-constraint, constraint-missing-not-valid
alter table documents add constraint documents_organisation_id_id_key unique (organisation_id, id);

create table voucher_documents (
  organisation_id uuid not null,
  voucher_id uuid not null,
  document_id uuid not null unique,
  primary key (voucher_id, document_id),
  foreign key (organisation_id, voucher_id) references vouchers (organisation_id, id) on delete cascade,
  foreign key (organisation_id, document_id) references documents (organisation_id, id)
);

